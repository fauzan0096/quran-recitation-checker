let language = 'roman';

export function getLanguage() {
  return language;
}

function stored() {
  try {
    return localStorage.getItem(STORAGE_KEY);
  } catch (error) {
    return null;
  }
}

/** Pick the stored language (or the device language) and apply it. */
export function initLanguage(preferred) {
  const saved = preferred || stored();
  if (saved && DICT[saved]) language = saved;
  else if (typeof navigator !== 'undefined' && /^ur/i.test(navigator.language || '')) language = 'ur';
  applyLanguage(language);
  return language;
}

export function setLanguage(next) {
  if (!DICT[next]) return language;
  language = next;
  try {
    localStorage.setItem(STORAGE_KEY, next);
  } catch (error) {
    /* private mode */
  }
  applyLanguage(next);
  return next;
}

/** Fill every data-i18n element in the document. */
export function applyLanguage(next = language) {
  if (!DICT[next]) return;
  language = next;
  document.documentElement.lang = next === 'ur' ? 'ur' : 'en';
  document.documentElement.dir = 'ltr';
  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const value = t(element.dataset.i18n);
    if (value) element.textContent = value;
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((element) => {
    const value = t(element.dataset.i18nPlaceholder);
    if (value) element.setAttribute('placeholder', value);
  });
  document.querySelectorAll('[data-lang-select]').forEach((select) => {
    select.value = next;
  });
}

/** Add extra strings to a language (used by strings-v2.js). */
export function addStrings(lang, strings) {
  if (!DICT[lang]) return;
  Object.assign(DICT[lang], strings);
}

/** Translate a key, with optional {placeholders}. */
export function t(key, vars) {
  const table = DICT[language] || DICT.roman;
  let value = table[key];
  if (value === undefined) value = DICT.roman[key];
  if (value === undefined) value = key;
  if (vars) {
    for (const [name, replacement] of Object.entries(vars)) {
      value = value.split(`{${name}}`).join(String(replacement));
    }
  }
  return value;
}
